from __future__ import annotations

from collections.abc import Awaitable, Callable, Iterable
from typing import Protocol

from app.models.awareness import (
    BriefingItem, BriefingPage, BriefingQuery, DevelopmentBatch, DevelopmentCandidate,
    Digest, ForbiddenCorpus, IndexReport, InternalScope, InternalSnapshot, ListResponse,
    MatchResult, Mitigation, MitigationCreate, MitigationPatch, OutboundWatchQuery,
    ProviderId, ProviderObservation, ReviewOutcome, ReviewOutcomeAction, ReviewPacket, SafeFetchLimits,
    SafeFetchResult, SavedView, Scan, ScanMode, ScanResult, SourceReference, SourceSupport,
    Watch, WatchDraftCreate, WatchPatch,
)


class OutboundQueryPolicy(Protocol):
    def prepare(self, watch: Watch, forbidden_corpus: ForbiddenCorpus) -> OutboundWatchQuery: ...


class SafeHttpFetcher(Protocol):
    async def fetch(self, url: str, limits: SafeFetchLimits) -> SafeFetchResult: ...


class WatchStore(Protocol):
    def create_draft(self, request: WatchDraftCreate) -> Watch: ...
    def get(self, watch_id: str) -> Watch: ...
    def list(self, cursor: str | None = None, limit: int = 25) -> ListResponse[Watch]: ...
    def update(self, watch_id: str, request: WatchPatch, expected_revision: int) -> Watch: ...
    def apply_scan_result(
        self, scan: Scan, checkpoints: dict[ProviderId, ProviderCheckpoint]
    ) -> Watch: ...


class DevelopmentService(Protocol):
    def record_candidates(
        self,
        watch_id: str,
        provider_id: str,
        candidates: Iterable[DevelopmentCandidate],
    ) -> DevelopmentBatch: ...


class BriefingStore(Protocol):
    def append_scan(self, scan: Scan) -> Scan: ...
    def append_observation(self, development_id: str, observation: ProviderObservation) -> None: ...
    def put_item(self, item: BriefingItem) -> BriefingItem: ...
    def put_view(self, view: SavedView) -> SavedView: ...
    def put_digest(self, digest: Digest) -> Digest: ...
    def get_item(self, item_id: str) -> BriefingItem: ...
    def get_view(self, view_id: str) -> SavedView: ...
    def get_digest(self, digest_id: str) -> Digest: ...
    def list_items(self, query: BriefingQuery) -> BriefingPage: ...
    def list_views(self, cursor: str | None = None, limit: int = 25) -> ListResponse[SavedView]: ...
    def list_digests(self, cursor: str | None = None, limit: int = 25) -> ListResponse[Digest]: ...


class MitigationService(Protocol):
    def list(self, matter_id: str) -> list[Mitigation]: ...
    def create(self, matter_id: str, request: MitigationCreate) -> Mitigation: ...
    def update(self, matter_id: str, mitigation_id: str, request: MitigationPatch, expected_revision: int) -> Mitigation: ...


class SourceSupportService(Protocol):
    async def check(self, source_reference: SourceReference) -> SourceSupport: ...


class InternalKnowledgeService(Protocol):
    def snapshot(self, internal_scope: InternalScope) -> InternalSnapshot: ...
    def forbidden_corpus(self, watch: Watch) -> ForbiddenCorpus: ...


class AwarenessMatcher(Protocol):
    def match(self, developments: DevelopmentBatch, snapshot: InternalSnapshot) -> MatchResult: ...


class ReviewPacketService(Protocol):
    def build(self, match_result: MatchResult) -> list[ReviewPacket]: ...


class ReviewOutcomeService(Protocol):
    def record_action(self, packet_id: str, action: ReviewOutcomeAction, payload: dict[str, object], expected_revision: int) -> ReviewOutcome: ...


class AwarenessIndex(Protocol):
    def rebuild(self) -> IndexReport: ...
    def query_briefing(self, query: BriefingQuery) -> BriefingPage: ...


class WatchScanService(Protocol):
    async def run_watch(self, watch_id: str, mode: ScanMode) -> ScanResult: ...
    def mark_interrupted_runs(self) -> int: ...


class BriefingQueryService(Protocol):
    def create_digest(self, view_id: str) -> Digest: ...


ScheduleRunner = Callable[[str], Awaitable[ScanResult | Digest]]
AgentRunner = Callable[[BriefingItem, str], Awaitable[object]]


class SchedulerService(Protocol):
    def bind_watch_runner(self, runner: ScheduleRunner) -> None: ...
    def bind_digest_runner(self, runner: ScheduleRunner) -> None: ...


class BriefingResearchService(Protocol):
    def bind_agent_runner(self, runner: AgentRunner) -> None: ...
